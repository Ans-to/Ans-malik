export const glyphFor = (ch: string): Glyph => G[ch.toUpperCase()] ?? G['?'];

export interface LayoutChar {
  ch: string;
  /** pen x at the start of the glyph (0-based, in em units) */
  x: number;
  w: number;
  index: number;
}

/** Monospaced-ish layout with tracking; returns pen positions in em units. */
export function layout(text: string, tracking = 0.16, spaceWidth = 0.34): { chars: LayoutChar[]; width: number } {
  let x = 0;
  const chars: LayoutChar[] = [];
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    const g = ch === ' ' ? { w: spaceWidth } : glyphFor(ch);
    chars.push({ ch, x, w: g.w, index: i });
    x += g.w + tracking;
  }
  const width = Math.max(0, x - tracking);
  return { chars, width };
}
