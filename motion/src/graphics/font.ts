/**
 * font.ts — a single-stroke ("Hershey-style") vector font, defined in code.
 *
 * Why not load a real typeface? Because this film is a neon wireframe piece:
 * letterforms made of lines *are* the aesthetic. Each glyph is a list of
 * polylines in a 1.0-unit cap-height box, so it can be scaled, skewed,
 * staggered per character and pushed through a 3D camera for free.
 */

export type Pt = [number, number];
export interface Glyph {
  w: number;
  strokes: Pt[][];
}

const arc = (cx: number, cy: number, rx: number, ry: number, a0: number, a1: number, steps = 14): Pt[] => {
  const pts: Pt[] = [];
  for (let i = 0; i <= steps; i++) {
    const a = ((a0 + (a1 - a0) * (i / steps)) * Math.PI) / 180;
    pts.push([cx + Math.cos(a) * rx, cy + Math.sin(a) * ry]);
  }
  return pts;
};

const ellipse = (cx: number, cy: number, rx: number, ry: number, steps = 22): Pt[] => arc(cx, cy, rx, ry, 0, 360, steps);

